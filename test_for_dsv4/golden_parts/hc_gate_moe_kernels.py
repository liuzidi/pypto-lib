def _flat_output(meta, kernel: str, name: str) -> np.ndarray:
    """Allocate a zeroed output buffer sized to the kernel's parsed elem count.

    Some .pto sub-kernels declare an ``i32`` accumulator as a *ptr* (e.g.
    exp_w2_mm's v1 = [16, D] i32 output). ``parse_pto`` classifies any ``i32``
    param as a scalar and skips its elem_count, so ``meta.elem_counts`` has no
    entry for it. Dynamic-shape ptrs (shape ``[%argN, ...]``) are likewise
    absent. In those cases the per-kernel ``_OUTPUT_COUNTS`` fallback
    ("<kernel>:<vN>") supplies the model-derived numel so the golden is still
    correctly shaped; the dtype falls back to float32 when meta lacks it.
    """
    count = meta.elem_counts.get(name)
    if not count:
        count = _OUTPUT_COUNTS.get(f"{kernel}:{name}", 0)
    np_type = meta.np_types.get(name, np.float32)
    return np.zeros(count, dtype=np_type)


