def _sh_gate_up_act_core(gate_i32, up_i32, x_scale_dq, w1_scale, w3_scale):
    """Shared SwiGLU: sh_h = silu(gate)*up, dequantized by per-row x scale x per-channel w scale."""
    gate = gate_i32.astype(np.float32) * x_scale_dq * w1_scale[None, :]
    up = up_i32.astype(np.float32) * x_scale_dq * w3_scale[None, :]
    if SWIGLU_LIMIT > 0:
        gate = np.minimum(gate, SWIGLU_LIMIT)
        up = np.maximum(np.minimum(up, SWIGLU_LIMIT), -SWIGLU_LIMIT)
    silu = gate * _sigmoid(gate)
    return silu * up


def build_sh_gate_up_act_q(meta, generator, ints):
    """sh_gate_up_act_q: fused SwiGLU + per-row INT8 requant.

    v1=x_local_scale_dq[T,1], v2=h_tile_fp32(out, [16, MOE_INTER]),
    v3=gate_i32[16, MOE_INTER], v4=up_i32[16, MOE_INTER], v5=shared_w1_scale,
    v6=shared_w3_scale, v7=h_tile_scale_dq(out, [16, 8]), v8=h_tile_i8(out, [16, MOE_INTER]).

    Computes h = silu(gate)*up (dequant), then per-row INT8 requant of h into
    h_tile_i8 + h_tile_scale_dq.
    """
    del ints
    (x_i8, x_sd, sw1, sw1s, sw3, sw3s, _sw2, _sw2s) = _gen_shared_inputs(generator)
    gate_i32 = x_i8.astype(np.int32) @ sw1.astype(np.int32).T
    up_i32 = x_i8.astype(np.int32) @ sw3.astype(np.int32).T
    h_full = _sh_gate_up_act_core(gate_i32, up_i32, x_sd, sw1s, sw3s)  # [T_DECODE, MOE_INTER]
    h_tile = np.zeros((T_PAD, MOE_INTER), dtype=np.float32)
    h_tile[:T_DECODE] = h_full
    h_i8, h_sd = _int8_quant_per_row(h_tile)        # h_sd = [16, 1]
    # h_tile_scale_dq buffer is [16, SH_ROW_PAD=8]; fill col 0 with h_sd.
    h_scale_dq_pad = np.zeros((T_PAD, 8), dtype=np.float32)
    h_scale_dq_pad[:, 0:1] = h_sd
    buffers = {
        "v1": x_sd.reshape(-1),
        "v2": _flat_output(meta, "sh_gate_up_act_q", "v2"),
        "v3": gate_i32.reshape(-1),
        "v4": up_i32.reshape(-1),
        "v5": sw1s.reshape(-1),
        "v6": sw3s.reshape(-1),
        "v7": _flat_output(meta, "sh_gate_up_act_q", "v7"),
        "v8": _flat_output(meta, "sh_gate_up_act_q", "v8"),
    }
    golden = {
        "v2": h_tile.reshape(-1),
        "v7": h_scale_dq_pad.reshape(-1),
        "v8": h_i8.reshape(-1),
    }
    return buffers, golden


def build_sh_w2_mm(meta, generator, ints):
    """sh_w2_mm: v1=h_tile_i8[16, MOE_INTER], v2=shared_w2[D, MOE_INTER], v3=y_i32(out, [16, D]).

    INT8 x INT8 -> INT32 cube matmul: y_i32 = h_tile_i8 @ shared_w2^T.
    """
    del ints
    (x_i8, x_sd, sw1, sw1s, sw3, sw3s, sw2, _sw2s) = _gen_shared_inputs(generator)
    gate_i32 = x_i8.astype(np.int32) @ sw1.astype(np.int32).T
    up_i32 = x_i8.astype(np.int32) @ sw3.astype(np.int32).T
    h_full = _sh_gate_up_act_core(gate_i32, up_i32, x_sd, sw1s, sw3s)
    h_tile = np.zeros((T_PAD, MOE_INTER), dtype=np.float32)
    h_tile[:T_DECODE] = h_full
    h_i8, _h_sd = _int8_quant_per_row(h_tile)
    y_i32 = h_i8.astype(np.int32) @ sw2.astype(np.int32).T   # [16, D]
    buffers = {
        "v1": h_i8.reshape(-1),
        "v2": sw2.reshape(-1),
        "v3": _flat_output(meta, "sh_w2_mm", "v3"),
    }
    golden = {"v3": y_i32.reshape(-1)}
    return buffers, golden


def build_sh_w2_act(meta, generator, ints):
    """sh_w2_act: v1=h_tile_scale_dq[16,8], v2=sh(out, bf16, [T,D]), v3=y_i32[16,D],
    v4=shared_w2_scale[D].

    Dequant w2 output: sh = y_i32 * max(h_scale_dq_row) * w2_scale, cast bf16.
    The kernel takes a row-max over the [16,8] h_tile_scale_dq (only col 0 valid)
    before applying it; we mirror that with np.max over axis=1.
    """
    del ints
    (x_i8, x_sd, sw1, sw1s, sw3, sw3s, sw2, sw2s) = _gen_shared_inputs(generator)
    gate_i32 = x_i8.astype(np.int32) @ sw1.astype(np.int32).T
    up_i32 = x_i8.astype(np.int32) @ sw3.astype(np.int32).T
    h_full = _sh_gate_up_act_core(gate_i32, up_i32, x_sd, sw1s, sw3s)
    h_tile = np.zeros((T_PAD, MOE_INTER), dtype=np.float32)
    h_tile[:T_DECODE] = h_full
    h_i8, h_sd = _int8_quant_per_row(h_tile)
    h_scale_dq_pad = np.zeros((T_PAD, 8), dtype=np.float32)
    h_scale_dq_pad[:, 0:1] = h_sd
    y_i32 = h_i8.astype(np.int32) @ sw2.astype(np.int32).T
    # row-max of h_tile_scale_dq (col 0 is the only valid col -> max == h_sd).
    h_scale_row = np.max(h_scale_dq_pad, axis=1, keepdims=True)   # [16, 1]
    sh = y_i32.astype(np.float32) * h_scale_row * sw2s[None, :]
    # sh output is [T_DECODE, D] (valid rows); pad rows T_DECODE..T_PAD stay 0.
    sh_out = np.zeros((T_DECODE, D), dtype=np.float32)
    sh_out[:T_DECODE] = sh[:T_DECODE]
    buffers = {
        "v1": h_scale_dq_pad.reshape(-1),
        "v2": _flat_output(meta, "sh_w2_act", "v2"),
        "v3": y_i32.reshape(-1),
        "v4": sw2s.reshape(-1),
    }
    golden = {"v2": float32_to_bf16(sh_out.reshape(-1))}
    return buffers, golden


