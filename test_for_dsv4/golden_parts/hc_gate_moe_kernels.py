"""DSV4 VPTO self-contained golden references for the hc_pre / hc_post / hc_head
and gate / MoE-expert kernel families (24 split-out sub-kernels).

Each ``build_<name>(meta, generator, ints)`` mirrors a single ``.pto`` sub-kernel
whose signature lives in ``test_for_dsv4/kernel_signatures.json`` and whose host
main.cpp is generated by ``vpto_run.py``. The functions return
``(buffers_dict, golden_dict)`` where:

* ``buffers_dict`` maps the vN names from the .pto signature to numpy arrays of
  the element counts/dtypes that ``validation_runtime.load_case_meta`` parsed
  from main.cpp. Inputs are random (seeded); outputs are zero-initialized so the
  harness can detect writes the kernel performs. bf16 tensors are stored as
  uint16, matching the bf16 representation used by ``float32_to_bf16``.
* ``golden_dict`` maps the *output* vN names to the torch-computed expected
  values. The comparison harness writes these to ``golden_vN.bin`` and compares
  them against the device's written ``vN.bin``.

The math is a direct port of the torch ``golden_*`` references in the DSV4 model
files (``models/deepseek_v4_pro/{hc_pre,hc_post,hc_head,gate,expert_routed,
expert_shared}.py``), specialized to the decode (B=4, S=2 -> T=8) shapes the .pto
sub-kernels are compiled for. Where a sub-kernel writes only a *slice* of a
full-tensor output (e.g. hc_pre_linear atomic-adds into mixes_raw), the golden
returns the full expected tensor so every written lane is covered.
"""

