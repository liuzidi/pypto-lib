def build_exp_w2_act(meta, generator, ints):
    """exp_w2_act: v1=recv_weights, v2=h_tile_scale_dq, v3=recv_y_tile(out, bf16),
    v4=y_i32, v5=routed_w2_scale.

    Dequant w2 output: recv_y = y_i32 * (h_scale * recv_weight) * w2_scale, cast bf16.
    """
    del ints
    (recv_x, recv_scale_dq, recv_weights, routed_w1, w1_scale, routed_w3, w3_scale, routed_w2, w2_scale) = _gen_routed_inputs(generator)
    gate_e = recv_x[0].astype(np.int32) @ routed_w1[0].astype(np.int32).T
    up_e = recv_x[0].astype(np.int32) @ routed_w3[0].astype(np.int32).T
    h_full = _exp_gate_up_act_core(
        gate_e, up_e, recv_scale_dq[0], w1_scale[0], w3_scale[0]
    )
    h_tile = h_full[:16]
    h_i8, h_sd = _int8_quant_per_row(h_tile)
    y_i32 = h_i8.astype(np.int32) @ routed_w2[0].astype(np.int32).T
    # row_scale_blk = h_sd * recv_weight (per-row, broadcast over D).
    w_per_row = recv_weights[0, :16].reshape(16, 1)
    row_scale = h_sd * w_per_row
    recv_y = y_i32.astype(np.float32) * row_scale * w2_scale[0][None, :]
    buffers = {
        "v1": recv_weights.reshape(-1),
        "v2": h_sd.reshape(-1),
        "v3": _flat_output(meta, "exp_w2_act", "v3"),
        "v4": y_i32.reshape(-1),
        "v5": w2_scale.reshape(-1),
    }
    golden = {"v3": float32_to_bf16(recv_y.reshape(-1))}
    return buffers, golden


