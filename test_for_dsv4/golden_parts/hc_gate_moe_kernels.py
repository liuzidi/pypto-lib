def _gen_routed_inputs(generator):
    """Random recv_x(i8), recv_scale_dq, recv_weights, routed_wN(i8)+scale matching
    build_tensor_specs in expert_routed.py. Weights are plain random int8 (the
    golden is a pure int32 matmul so the weight distribution does not matter for
    correctness; the model's gen_routed_weight grid sim is a perf/realism
    concern, not a precision-test concern)."""
    recv_x = make_i8(generator, N_LOCAL_EXPERTS * RECV_MAX * D).reshape(N_LOCAL_EXPERTS, RECV_MAX, D)
    recv_scale_dq = make_fp32(generator, N_LOCAL_EXPERTS * RECV_MAX, scale=0.05).reshape(N_LOCAL_EXPERTS, RECV_MAX)
    recv_weights = generator.uniform(0.0, 1.0, size=(N_LOCAL_EXPERTS, RECV_MAX)).astype(np.float32)
    routed_w1 = make_i8(generator, N_LOCAL_EXPERTS * MOE_INTER * D).reshape(N_LOCAL_EXPERTS, MOE_INTER, D)
    routed_w1_scale = make_fp32(generator, N_LOCAL_EXPERTS * MOE_INTER, scale=0.05).reshape(N_LOCAL_EXPERTS, MOE_INTER)
    routed_w3 = make_i8(generator, N_LOCAL_EXPERTS * MOE_INTER * D).reshape(N_LOCAL_EXPERTS, MOE_INTER, D)
    routed_w3_scale = make_fp32(generator, N_LOCAL_EXPERTS * MOE_INTER, scale=0.05).reshape(N_LOCAL_EXPERTS, MOE_INTER)
    routed_w2 = make_i8(generator, N_LOCAL_EXPERTS * D * MOE_INTER).reshape(N_LOCAL_EXPERTS, D, MOE_INTER)
    routed_w2_scale = make_fp32(generator, N_LOCAL_EXPERTS * D, scale=0.05).reshape(N_LOCAL_EXPERTS, D)
    return (recv_x, recv_scale_dq, recv_weights,
            routed_w1, routed_w1_scale, routed_w3, routed_w3_scale,
            routed_w2, routed_w2_scale)


def build_exp_gate_mm(meta, generator, ints):
    """exp_gate_mm: v1=gate_e(out, i32), v2=recv_x(i8), v3=routed_w1(i8).

    INT8 x INT8 -> INT32 cube matmul: gate_e[RECV_MAX, MOE_INTER] = recv_x @ w1^T.
    Local-expert axis is flattened: v1 is [N_LOCAL_EXPERTS*RECV_MAX, MOE_INTER].
    """
    del ints
    (recv_x, _rsd, _rw, routed_w1, _w1s, _w3, _w3s, _w2, _w2s) = _gen_routed_inputs(generator)
    gate_e = np.zeros((N_LOCAL_EXPERTS * RECV_MAX, MOE_INTER), dtype=np.int32)
    for e in range(N_LOCAL_EXPERTS):
        gate_e[e * RECV_MAX:(e + 1) * RECV_MAX] = (
            recv_x[e].astype(np.int32) @ routed_w1[e].astype(np.int32).T
        )
    buffers = {
        "v1": _flat_output(meta, "exp_gate_mm", "v1"),
        "v2": recv_x.reshape(-1),
        "v3": routed_w1.reshape(-1),
    }
    golden = {"v1": gate_e.reshape(-1)}
    return buffers, golden


