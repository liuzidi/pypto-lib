def build_hc_head_pre_fused(meta, generator, ints):
    """hc_head_pre_fused: scale+sigmoid+transpose -> pre_t.

    v1=hc_head_scale[1], v2=hc_head_base[HC_MULT], v3=pre_t[HC_HEAD_PAD, T_MAX](out),
    v4=mixes_raw[T_MAX, HC_HEAD_PAD], v5=inv_rms[T_MAX,1].
    pre = sigmoid(mixes * inv_rms * scale + base) + HC_EPS, transposed into pre_t.
    """
    del ints
    t_dim = T_DECODE
    t_max = 128   # hc_head intermediates are padded to T_MAX
    x_hc, hc_head_fn, hc_head_scale, hc_head_base = _gen_hc_head_inputs(generator, t_dim)
    inv_rms = _hc_head_rms_core(x_hc, t_dim)
    mixes = _hc_head_linear_core(x_hc, hc_head_fn, t_dim)
    # pre operates on the HC_MULT valid columns of mixes (hc_head_base is [HC_MULT]).
    pre = _sigmoid(mixes[:, :HC_MULT] * inv_rms * hc_head_scale[0] + hc_head_base) + HC_EPS
    # Pad the input intermediates to T_MAX so v4/v5 match the .pto buffer sizes.
    mixes_pad = np.zeros((t_max, HC_HEAD_PAD), dtype=np.float32)
    mixes_pad[:t_dim] = mixes
    inv_rms_pad = np.zeros((t_max, 1), dtype=np.float32)
    inv_rms_pad[:t_dim] = inv_rms
    # pre_t is [HC_HEAD_PAD, T_MAX] with HC_MULT valid rows.
    pre_t = np.zeros((HC_HEAD_PAD, t_max), dtype=np.float32)
    pre_t[:HC_MULT, :t_dim] = pre.T
    buffers = {
        "v1": hc_head_scale.reshape(-1),
        "v2": hc_head_base.reshape(-1),
        "v3": _flat_output(meta, "hc_head_pre_fused", "v3"),
        "v4": mixes_pad.reshape(-1),
        "v5": inv_rms_pad.reshape(-1),
    }
    golden = {"v3": pre_t.reshape(-1)}
    return buffers, golden


def build_hc_head_reduce(meta, generator, ints):
    """hc_head_reduce: pre_t @ x_flat^T (per-head row-broadcast) -> y (bf16).

    v1=pre_t[HC_HEAD_PAD, T], v2=y[T,D] bf16 (out), v3=x[T,HC_DIM].
    y = sum_h x[:,h,:] * pre[:,h] (HC_MULT==4 hardcoded reduce).
    """
    del ints
    t_dim = T_DECODE
    x_hc, hc_head_fn, hc_head_scale, hc_head_base = _gen_hc_head_inputs(generator, t_dim)
    inv_rms = _hc_head_rms_core(x_hc, t_dim)
    mixes = _hc_head_linear_core(x_hc, hc_head_fn, t_dim)
    pre = _sigmoid(mixes[:, :HC_MULT] * inv_rms * hc_head_scale[0] + hc_head_base) + HC_EPS
    y0 = x_hc[:, 0, :] * pre[:, 0:1]
    y1 = x_hc[:, 1, :] * pre[:, 1:2]
    y2 = x_hc[:, 2, :] * pre[:, 2:3]
    y3 = x_hc[:, 3, :] * pre[:, 3:4]
    y = (y0 + y1) + (y2 + y3)
    t_max = 128
    pre_t = np.zeros((HC_HEAD_PAD, t_max), dtype=np.float32)
    pre_t[:HC_MULT, :t_dim] = pre.T
    buffers = {
        "v1": pre_t.reshape(-1),
        "v2": _flat_output(meta, "hc_head_reduce", "v2"),
        "v3": x_hc.reshape(-1),
    }
    golden = {"v2": float32_to_bf16(y.reshape(-1))}
    return buffers, golden


