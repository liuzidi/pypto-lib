def _gen_hc_head_inputs(generator, t_dim):
    """Random x_hc, hc_head_fn, scale, base matching build_tensor_specs in hc_head.py."""
    x_hc = make_fp32(generator, t_dim * HC_MULT * D, scale=0.05).reshape(t_dim, HC_MULT, D)
    hc_head_fn = make_fp32(generator, HC_MULT * HC_DIM, scale=0.0519).reshape(HC_MULT, HC_DIM)
    hc_head_scale = np.array([0.076099], dtype=np.float32)
    hc_head_base = np.array([5.9166, -3.6223, -2.9324, -3.3124], dtype=np.float32)
    return x_hc, hc_head_fn, hc_head_scale, hc_head_base


def _hc_head_rms_core(x_hc, t_dim):
    """inv_rms = rsqrt(mean(x_flat^2)+eps), x_flat=[T,HC_DIM]."""
    x_flat = x_hc.reshape(t_dim, HC_DIM)
    sq_sum = np.zeros((t_dim, 1), dtype=np.float32)
    for k0 in range(0, HC_DIM, HC_HEAD_RMS_K_CHUNK):
        x_chunk = x_flat[:, k0:k0 + HC_HEAD_RMS_K_CHUNK]
        sq_sum += np.sum(x_chunk * x_chunk, axis=1, keepdims=True)
    return np.reciprocal(np.sqrt(sq_sum * HC_DIM_INV + NORM_EPS))


def _hc_head_linear_core(x_hc, hc_head_fn, t_dim):
    """mixes = x_flat @ hc_head_fn^T, [T, HC_HEAD_PAD], per-K-chunk accumulation.

    Returns the padded [T, HC_HEAD_PAD] layout (HC_MULT=4 valid cols, rest 0)
    matching the .pto mixes_raw buffer's column width.
    """
    x_flat = x_hc.reshape(t_dim, HC_DIM)
    mixes = np.zeros((t_dim, HC_HEAD_PAD), dtype=np.float32)
    for h in range(HC_MULT):
        col = np.zeros((t_dim, 1), dtype=np.float32)
        for k0 in range(0, HC_DIM, HC_HEAD_LINEAR_K_CHUNK):
            x_chunk = x_flat[:, k0:k0 + HC_HEAD_LINEAR_K_CHUNK]
            w_chunk = hc_head_fn[h:h + 1, k0:k0 + HC_HEAD_LINEAR_K_CHUNK]
            col += np.sum(x_chunk * w_chunk, axis=1, keepdims=True)
        mixes[:, h:h + 1] = col
    return mixes


def build_hc_head_rms(meta, generator, ints):
    """hc_head_rms: v1=x[T,HC_DIM] fp32 (input), v2=inv_rms[T_MAX,1] fp32 (output).

    The .pto stores inv_rms in a [T_MAX=128, 1] buffer (padded for the head
    projection's T_MAX-shaped intermediates); the per-token inv_rms is valid for
    the first T_DECODE rows and zero-padded for the rest.
    """
    del ints
    t_dim = T_DECODE
    t_max = 128
    x_hc, _fn, _sc, _b = _gen_hc_head_inputs(generator, t_dim)
    inv_rms = _hc_head_rms_core(x_hc, t_dim)
    inv_rms_pad = np.zeros((t_max, 1), dtype=np.float32)
    inv_rms_pad[:t_dim] = inv_rms
    buffers = {"v1": x_hc.reshape(-1), "v2": _flat_output(meta, "hc_head_rms", "v2")}
    golden = {"v2": inv_rms_pad.reshape(-1)}
    return buffers, golden


