def _gen_gate_inputs(generator, num_tokens=T_DECODE, layer_id=N_HASH_LAYERS):
    """Random x_mixed, norm_w, gate_w, gate_bias, tid2eid, input_ids matching
    build_tensor_specs in gate.py (decode T=8 active tokens).

    x_mixed is the [T_DECODE, D] bf16 activation entering the router. The
    router's padded intermediates (xg, inv_rms, xn_scale at [T_PAD, ...]) are
    produced by _ffn_norm_core padding the per-token computation to T_PAD.
    """
    x_mixed = float32_to_bf16(
        generator.standard_normal(T_DECODE * D).astype(np.float32)
    ).reshape(T_DECODE, D)
    norm_w = float32_to_bf16(np.ones(D, dtype=np.float32))
    gate_w = (generator.standard_normal(N_EXPERTS * D).astype(np.float32) / np.sqrt(D)).reshape(N_EXPERTS, D)
    gate_bias = (generator.standard_normal(N_EXPERTS).astype(np.float32) * 0.1)
    tid2eid = generator.integers(0, N_EXPERTS, size=(VOCAB, TOPK), dtype=np.int32)
    input_ids = generator.integers(0, VOCAB, size=(T_DECODE,), dtype=np.int64)
    return x_mixed, norm_w, gate_w, gate_bias, tid2eid, input_ids


def _ffn_norm_core(x_mixed_bf16, norm_w_bf16, num_tokens):
    """Deferred RMSNorm (qwen3-style): xg = bf16(x*gamma), inv_rms scalar folded
    downstream. Returns (xg[T_PAD,D], inv_rms[T_PAD,1], x_norm_i8[T_PAD,D],
    x_norm_scale[T_DECODE,1], scale_dq_g[T_PAD,1]).

    Inputs x_mixed/norm_w are [T_DECODE, D]; outputs are padded to T_PAD so they
    match the .pto's padded intermediate buffer sizes (xg, inv_rms, xn_scale at
    T_PAD=16 rows). x_norm_scale is [T_DECODE, 1] (the active-row output, which
    the kernel guards to active tokens).
    """
    x_f = bf16_to_float32(x_mixed_bf16.reshape(-1, 1)).reshape(T_DECODE, D) \
        if x_mixed_bf16.dtype == np.uint16 else x_mixed_bf16.astype(np.float32)
    nw = bf16_to_float32(norm_w_bf16.reshape(-1, 1)).reshape(D) \
        if norm_w_bf16.dtype == np.uint16 else norm_w_bf16.astype(np.float32)
    sq_sum = np.sum(x_f * x_f, axis=-1, keepdims=True).astype(np.float32)
    inv_rms_active = np.reciprocal(np.sqrt(sq_sum * (np.float32(1.0) / D) + NORM_EPS))
    xg_active = x_f * nw.reshape(1, D)
    # per-token symmetric INT8 quant of xg; inv_rms cancels in the int8 values.
    x_norm_i8_active, scale_dq_g_active = _int8_quant_per_row(xg_active)
    x_norm_scale = (scale_dq_g_active.reshape(T_DECODE, 1) * inv_rms_active)
    if num_tokens < T_DECODE:
        x_norm_scale[num_tokens:] = 0
    # Pad intermediates to T_PAD (the .pto xg/inv_rms/xn_scale buffer rows).
    xg = np.zeros((T_PAD, D), dtype=np.float32)
    xg[:T_DECODE] = xg_active
    inv_rms = np.zeros((T_PAD, 1), dtype=np.float32)
    inv_rms[:T_DECODE] = inv_rms_active
    x_norm_i8 = np.zeros((T_PAD, D), dtype=np.int8)
    x_norm_i8[:T_DECODE] = x_norm_i8_active
    scale_dq_g = np.zeros((T_PAD, 1), dtype=np.float32)
    scale_dq_g[:T_DECODE] = scale_dq_g_active
    return xg, inv_rms, x_norm_i8, x_norm_scale, scale_dq_g


def _gate_core(xg, inv_rms, gate_w, gate_bias):
    """sqrtsoftplus router score: logits = inv_rms * (xg @ gate_w^T);
    scores = sqrt(softplus(logits)); biased = scores + gate_bias."""
    logits = inv_rms * (xg @ gate_w.T)
    softplus = _softplus_stable(logits)
    scores = np.sqrt(softplus)
    biased = scores + gate_bias.reshape(1, -1)
    return scores, biased


def build_ffn_norm(meta, generator, ints):
    """ffn_norm: v1=x_mixed(bf16), v2=norm_w(bf16), v3=xg(out), v4=inv_rms(out),
    v5=x_norm_scale(out), v6=xn_scale(out).

    One token per core: deferred RMSNorm + amax + quant-scale. Outputs xg (not
    yet *inv_rms), inv_rms, x_norm_scale (= inv_rms * amax(xg)/127), xn_scale
    (= 127 / amax(xg)).
    """
    del ints
    x_mixed, norm_w, _gw, _gb, _t2e, _ids = _gen_gate_inputs(generator)
    xg, inv_rms, _x_norm_i8, x_norm_scale, scale_dq_g = _ffn_norm_core(x_mixed, norm_w, T_PAD)
    xn_scale = np.reciprocal(scale_dq_g)              # = 127 / amax(xg)
    buffers = {
        "v1": x_mixed.reshape(-1),
        "v2": norm_w.reshape(-1),
        "v3": _flat_output(meta, "ffn_norm", "v3"),
        "v4": _flat_output(meta, "ffn_norm", "v4"),
        "v5": _flat_output(meta, "ffn_norm", "v5"),
        "v6": _flat_output(meta, "ffn_norm", "v6"),
    }
    # v3=xg, v4=inv_rms, v5=x_norm_scale, v6=xn_scale (all [T,1 or D] flat).
    golden = {
        "v3": xg.reshape(-1),
        "v4": inv_rms.reshape(-1),
        "v5": x_norm_scale.reshape(-1),
        "v6": xn_scale.reshape(-1),
    }
    return buffers, golden


def build_gate(meta, generator, ints):
    """gate (gate_aic): v1=gate_bias, v2=xg, v3=gate_w, v4=inv_rms, v5=route_scores(out).

    Cube matmul xg @ gate_w^T -> logits; sqrtsoftplus -> scores; row-scale by
    inv_rms. Writes route_scores[T_PAD, SCORE_PAD] (N_EXPERTS valid cols, rest
    unused in this sub-kernel; gate_pre_route pads them -inf).
    """
    del ints
    x_mixed, norm_w, gate_w, gate_bias, _t2e, _ids = _gen_gate_inputs(generator)
    xg, inv_rms, _i8, _xns, _sd = _ffn_norm_core(x_mixed, norm_w, T_PAD)
    scores, _biased = _gate_core(xg, inv_rms, gate_w, gate_bias)
    # The .pto route_scores buffer is [T_PAD, SCORE_PAD]; fill valid cols with
    # scores, leave the pad tail at 0 (gate_pre_route will -inf it).
    route_scores = np.zeros((T_PAD, SCORE_PAD), dtype=np.float32)
    route_scores[:, :N_EXPERTS] = scores
    buffers = {
        "v1": gate_bias.reshape(-1),
        "v2": xg.reshape(-1),
        "v3": gate_w.reshape(-1),
        "v4": inv_rms.reshape(-1),
        "v5": _flat_output(meta, "gate", "v5"),
    }
    golden = {"v5": route_scores.reshape(-1)}
    return buffers, golden


def build_gate_pre_route(meta, generator, ints):
    """gate_pre_route: v1=biased_scores[T_PAD, SCORE_PAD] (output, init -inf pad).

    The kernel zeros inactive-token outputs and -inf-fills the biased_scores pad
    columns [N_EXPERTS:SCORE_PAD] so the sort ranks pad experts last. With no
    inactive tokens (num_tokens=T) the only write is the -inf pad tail.
    Golden = the full biased_scores with the -inf pad tail (valid cols left at
    whatever the input was; we generate them as the post-gate biased scores for a
    self-contained check).
    """
    del ints
    x_mixed, norm_w, gate_w, gate_bias, _t2e, _ids = _gen_gate_inputs(generator)
    xg, inv_rms, _i8, _xns, _sd = _ffn_norm_core(x_mixed, norm_w, T_PAD)
    _scores, biased = _gate_core(xg, inv_rms, gate_w, gate_bias)
    biased_scores = np.zeros((T_PAD, SCORE_PAD), dtype=np.float32)
    biased_scores[:, :N_EXPERTS] = biased
    biased_scores[:, N_EXPERTS:] = FP32_NEG_INF
    buffers = {"v1": _flat_output(meta, "gate_pre_route", "v1")}
    golden = {"v1": biased_scores.reshape(-1)}
    return buffers, golden


def build_route_hash(meta, generator, ints):
    """route_hash: v1=input_ids, v2=tid2eid, v3=route_scores, v4=indices(out),
    v5=weights(out).

    Hash layers (layer_id < N_HASH_LAYERS): indices = tid2eid[input_ids];
    weights = gather(scores, indices) / sum * ROUTE_SCALE.
    """
    del ints
    x_mixed, norm_w, gate_w, gate_bias, tid2eid, input_ids = _gen_gate_inputs(generator, layer_id=0)
    xg, inv_rms, _i8, _xns, _sd = _ffn_norm_core(x_mixed, norm_w, T_PAD)
    scores, _biased = _gate_core(xg, inv_rms, gate_w, gate_bias)
    indices = tid2eid[input_ids[:T_DECODE]]            # [T, TOPK]
    topk_vals = np.take_along_axis(scores[:T_DECODE], indices.astype(np.int64), axis=1)
    denom = topk_vals.sum(axis=-1, keepdims=True)
    weights = (topk_vals / denom) * ROUTE_SCALE
    # route_scores buffer is [T_PAD, SCORE_PAD]; pad tail 0.
    route_scores = np.zeros((T_PAD, SCORE_PAD), dtype=np.float32)
    route_scores[:, :N_EXPERTS] = scores
    buffers = {
        "v1": input_ids[:T_DECODE].reshape(-1),
        "v2": tid2eid.reshape(-1),
        "v3": route_scores.reshape(-1),
        "v4": _flat_output(meta, "route_hash", "v4"),
        "v5": _flat_output(meta, "route_hash", "v5"),
    }
    golden = {
        "v4": indices.astype(np.int32).reshape(-1),
        "v5": weights.astype(np.float32).reshape(-1),
    }
    return buffers, golden


def build_x_norm_quant(meta, generator, ints):
    """x_norm_quant: v1=xn_scale[T_PAD,1], v2=x_norm_i8[T,D] (out), v3=xg[T,D].

    Per-token symmetric INT8 quant of xg using the precomputed xn_scale
    (= 127 / amax(xg)) from ffn_norm. inv_rms cancels in the int8 values.
    """
    del ints
    x_mixed, norm_w, _gw, _gb, _t2e, _ids = _gen_gate_inputs(generator)
    xg, _inv_rms, x_norm_i8, _xns, scale_dq_g = _ffn_norm_core(x_mixed, norm_w, T_PAD)
    xn_scale = np.reciprocal(scale_dq_g).reshape(T_PAD, 1)
    buffers = {
        "v1": xn_scale.reshape(-1),
        "v2": _flat_output(meta, "x_norm_quant", "v2"),
        "v3": xg.reshape(-1),
    }
    golden = {"v2": x_norm_i8[:T_DECODE].reshape(-1)}
    return buffers, golden


