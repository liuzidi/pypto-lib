    """exp_up_mm: v1=up_e(out, i32), v2=recv_x(i8), v3=routed_w3(i8).

    Same as exp_gate_mm but with w3. v1 is [N_LOCAL_EXPERTS*RECV_MAX, MOE_INTER].
    """
