def make_fp32(generator, count: int, *, scale: float = 0.05, positive: bool = False) -> np.ndarray:
    if positive:
        return generator.uniform(0.25, 1.5, size=count).astype(np.float32)
    return generator.uniform(-scale, scale, size=count).astype(np.float32)


def make_bf16(generator, count: int, *, scale: float = 0.05, positive: bool = False) -> np.ndarray:
    return float32_to_bf16(make_fp32(generator, count, scale=scale, positive=positive))


def make_i8(generator, count: int, *, scale: float = 1.0) -> np.ndarray:
    """Random int8 in [-127, 127], stored as int8 (kernel weight / activation).

    generator.integers(-127, 128) yields values in [-127, 127] inclusive; the
    int32->int8 cast is a no-op for that range (no overflow wrap)."""
    vals = generator.integers(-127, 128, size=count, dtype=np.int8)
    return vals


def _sigmoid(x):
    return np.reciprocal(np.float32(1.0) + np.exp(-x))


def _softplus_stable(x):
    """log1p(exp(-|x|)) + relu(x) = softplus, stable for large |x|."""
    return np.maximum(x, 0.0) + np.log1p(np.exp(-np.abs(x)))


def _int8_quant_per_row(x_f32):
    """Per-row symmetric INT8 quant matching the kernel's cast chain:
    round -> int32 -> fp16(round) -> int8(trunc). Returns (i8, scale_dequant[T,1])."""
    rows = x_f32.reshape(-1, x_f32.shape[-1])
    amax = np.max(np.abs(rows), axis=-1, keepdims=True)
    amax = np.maximum(amax, INT8_AMAX_EPS)
    scale_q = (np.float32(INT8_SCALE_MAX) / amax).astype(np.float32)
    scaled = rows * scale_q
    i32 = np.round(scaled).astype(np.int32)
    # kernel chain: i32 -> fp16(round) -> i8(trunc). numpy int32->int8 truncates,
    # matching the int8 result since fp16 round of a value already rounded to
    # int32 is a no-op for the |q| <= 127 range enforced by scale_q.
    i8 = i32.astype(np.int8)
    scale_dq = np.reciprocal(scale_q)
    return i8.reshape(x_f32.shape), scale_dq.reshape(*x_f32.shape[:-1], 1)


# ======================================================================================
# hc_pre family (rms / seed / linear sub-kernels; fused build_hc_pre_fused covers all)
# ======================================================================================
# The .pto hc_pre sub-kernels write into three shared intermediates (mixes_raw,
# inv_rms, post, comb, x_mixed) that the fused _hc_pre_separate computes
# end-to-end. Each sub-kernel test exercises only that stage's writes, so each
# build_ function generates the full fused golden and returns only the slice the
# sub-kernel is expected to produce. Where a sub-kernel only reads its inputs
# (e.g. hc_pre_seed writes zeros), the golden is the zero-filled output buffer.


def _hc_pre_fused_golden(x_fp32, hc_fn, hc_scale, hc_base, t_dim):
    """Compute the full hc_pre fused output (matches golden_hc_pre in hc_pre.py).

    Returns (x_mixed_bf16_uint16, post_fp32, comb_fp32, inv_rms_fp32, mixes_raw_fp32).
    """
    x_flat = x_fp32.reshape(t_dim, HC_DIM)
    # RMS: sum of squares over HC_DIM, rsqrt(+eps).
    sq_sum = np.zeros((t_dim, 1), dtype=np.float32)
    for k0 in range(0, HC_DIM, RMS_K_CHUNK):
        x_chunk = x_flat[:, k0:k0 + RMS_K_CHUNK]
        sq_sum += np.sum(x_chunk * x_chunk, axis=1, keepdims=True)
    inv_rms = np.reciprocal(np.sqrt(sq_sum * HC_DIM_INV + NORM_EPS))

    # Linear: split-K matmul x_flat @ hc_fn^T -> mixes_raw[T, MIX_HC].
    # Accumulate per-K-chunk partial dots then sum to match cube K-fragment order.
    n_chunk = HC_DIM // LINEAR_K_CHUNK
    x_k = x_flat.reshape(t_dim, 1, n_chunk, LINEAR_K_CHUNK)
    w_k = hc_fn.reshape(1, MIX_HC, n_chunk, LINEAR_K_CHUNK)
    per_chunk = np.sum(x_k * w_k, axis=3)            # [T, MIX_HC, n_chunk]
    mixes = np.zeros((t_dim, MIX_HC), dtype=np.float32)
    for c in range(n_chunk):
        mixes += per_chunk[:, :, c]
    mixes_raw = mixes.copy()                          # pre-inv_rms mixes
    mixes = mixes * inv_rms                           # post-inv_rms (gate inputs)

    pre = _sigmoid(mixes[:, :HC_MULT] * hc_scale[0] + hc_base[:HC_MULT]) + HC_EPS
    post_t = np.float32(2.0) * _sigmoid(
        mixes[:, HC_MULT:HC_MULT * 2] * hc_scale[1] + hc_base[HC_MULT:HC_MULT * 2]
    )
    comb_t = (mixes[:, HC_MULT * 2:] * hc_scale[2] + hc_base[HC_MULT * 2:]).reshape(
        t_dim, HC_MULT, HC_MULT
    )

    # softmax over last axis, then Sinkhorn (column-first, 20 iters).
    comb_t = _softmax_last_axis(comb_t) + HC_EPS
    comb_t = comb_t / (comb_t.sum(axis=-2, keepdims=True) + HC_EPS)
    for _ in range(HC_SINKHORN_ITER - 1):
        comb_t = comb_t / (comb_t.sum(axis=-1, keepdims=True) + HC_EPS)
        comb_t = comb_t / (comb_t.sum(axis=-2, keepdims=True) + HC_EPS)

    # mix_x: x_mixed = sum_h pre[:,h] * x[:,h,:]
    y0 = x_fp32[:, 0, :] * pre[:, 0:1]
    y1 = x_fp32[:, 1, :] * pre[:, 1:2]
    y2 = x_fp32[:, 2, :] * pre[:, 2:3]
    y3 = x_fp32[:, 3, :] * pre[:, 3:4]
    y = (y0 + y1) + (y2 + y3)
    x_mixed = float32_to_bf16(y.reshape(t_dim, D))
    return x_mixed, post_t, comb_t.reshape(t_dim, HC_MULT * HC_MULT), inv_rms, mixes_raw


def _softmax_last_axis(x):
    m = np.max(x, axis=-1, keepdims=True)
    e = np.exp(x - m)
    return e / np.sum(e, axis=-1, keepdims=True)


def _gen_hc_pre_inputs(generator, t_dim):
    """Random x, hc_fn, hc_scale, hc_base matching build_tensor_specs in hc_pre.py."""
    x = make_fp32(generator, t_dim * HC_MULT * D, scale=0.05).reshape(t_dim, HC_MULT, D)
    hc_fn = make_fp32(generator, MIX_HC * HC_DIM, scale=0.0519).reshape(MIX_HC, HC_DIM)
    hc_scale = np.array([0.076099, 0.032597, 0.226994], dtype=np.float32)
    hc_base = np.array([
        5.9166, -3.6223, -2.9324, -3.3124,
        -3.9100, -0.9384, -3.3256, -2.5240,
        2.0706, -2.5728, 0.1424, -3.9453,
        -3.8859, 3.4634, -3.3799, -2.6077,
        -2.7191, -2.4846, 2.0395, -0.5010,
        -3.5992, -2.7520, -3.3493, 3.1587,
    ], dtype=np.float32)
    return x, hc_fn, hc_scale, hc_base


def build_hc_pre_fused(meta, generator, ints):
    """Fused hc_pre reference (the full _hc_pre_separate math).

    The .pto has no single 'hc_pre_fused' sub-kernel (the fused syncall variant
    is device-specialized and skipped on sim); this builder is the canonical
    golden used by the sub-kernel builders below to derive their slices.
    """
    del ints
    t_dim = T_DECODE
    x, hc_fn, hc_scale, hc_base = _gen_hc_pre_inputs(generator, t_dim)
    x_mixed, post, comb, inv_rms, mixes_raw = _hc_pre_fused_golden(
        x, hc_fn, hc_scale, hc_base, t_dim
    )
    buffers = {
        "v1": x.reshape(-1),
        "v2": hc_fn.reshape(-1),
        "v3": hc_scale,
        "v4": hc_base,
    }
    golden = {
        "v5": x_mixed.reshape(-1),
        "v6": post.reshape(-1),
        "v7": comb.reshape(-1),
    }
    return buffers, golden


def build_hc_pre_rms(meta, generator, ints):
    """hc_pre_rms: v1=x[T,HC_DIM] fp32 (input), v2=inv_rms[T,1] fp32 (output).

    Computes the per-token rsqrt(mean(x^2)+eps). The .pto stores inv_rms in a
    transposed [T,1] dn-layout buffer; the golden is the flat [T,1] column so
    the compare covers every token's inv_rms.
    """
    del ints
    t_dim = T_DECODE
    x, _hc_fn, _hc_scale, _hc_base = _gen_hc_pre_inputs(generator, t_dim)
    x_flat = x.reshape(t_dim, HC_DIM)
    sq_sum = np.zeros((t_dim, 1), dtype=np.float32)
    for k0 in range(0, HC_DIM, RMS_K_CHUNK):
        x_chunk = x_flat[:, k0:k0 + RMS_K_CHUNK]
        sq_sum += np.sum(x_chunk * x_chunk, axis=1, keepdims=True)
    inv_rms = np.reciprocal(np.sqrt(sq_sum * HC_DIM_INV + NORM_EPS))
    buffers = {"v1": x_flat.reshape(-1), "v2": _flat_output(meta, "hc_pre_rms", "v2")}
    golden = {"v2": inv_rms.reshape(-1)}
    return buffers, golden


def build_hc_pre_seed(meta, generator, ints):
    """hc_pre_seed: v1=mixes_raw[t_linear, MIX_PAD] fp32 (output, zero-filled).

    The kernel writes zeros into the split-K atomic-add accumulator so the
    subsequent hc_pre_linear atomic-adds start from a clean state. Golden is
    the zero buffer of the parsed element count.
    """
    del ints
    zero_buf = _flat_output(meta, "hc_pre_seed", "v1")
    buffers = {"v1": zero_buf}
    golden = {"v1": np.zeros(zero_buf.size, dtype=np.float32)}
    return buffers, golden


def build_hc_pre_linear(meta, generator, ints):
    """hc_pre_linear: v1=x[T,HC_DIM], v2=hc_fn[MIX_HC,HC_DIM], v3=mixes_raw (output).

    Split-K matmul x @ hc_fn^T -> mixes_raw[T, MIX_HC], atomic-added from zero-seed.
    Golden returns the full mixes_raw (pre-inv_rms) so every spmd block's partial
    is covered.
    """
    del ints
    t_dim = T_DECODE
    x, hc_fn, _hc_scale, _hc_base = _gen_hc_pre_inputs(generator, t_dim)
    x_flat = x.reshape(t_dim, HC_DIM)
    # Per-K-chunk dot accumulation to match cube K-fragment order.
    n_chunk = HC_DIM // LINEAR_K_CHUNK
    x_k = x_flat.reshape(t_dim, 1, n_chunk, LINEAR_K_CHUNK)
    w_k = hc_fn.reshape(1, MIX_HC, n_chunk, LINEAR_K_CHUNK)
    per_chunk = np.sum(x_k * w_k, axis=3)
    mixes = np.zeros((t_dim, MIX_HC), dtype=np.float32)
    for c in range(n_chunk):
        mixes += per_chunk[:, :, c]
    buffers = {
        "v1": x_flat.reshape(-1),
        "v2": hc_fn.reshape(-1),
        "v3": _flat_output(meta, "hc_pre_linear", "v3"),
    }
    golden = {"v3": mixes.reshape(-1)}
    return buffers, golden


